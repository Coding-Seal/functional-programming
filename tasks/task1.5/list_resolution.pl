%
% Обозначения: R_i резольвента (текущий набор подцелей) после шага i.

% ### Запрос: list([1,2]).
%
% R_0 = { list([1,2]) }
%
% Шаг 1. Пробуем базовый факт.
% Подцель: list([1,2])
% Правило: list([])
% Подстановка: не существует, [1,2] не совпадает с []
% Факт не подходит, список непуст.
%
% Шаг 1 (продолжение). Применяем рекурсивное правило, снимаем голову 1.
% Подцель: list([1,2])
% Правило: list([H|T]) :- list(T)
% Подстановка: H/1, T/[2]
% R_1 = { list([2]) }
%
% Шаг 2. Пробуем базовый факт.
% Подцель: list([2])
% Правило: list([])
% Подстановка: не существует, [2] не совпадает с []
% Факт не подходит, список непуст.
%
% Шаг 2 (продолжение). Применяем рекурсивное правило, снимаем голову 2.
% Подцель: list([2])
% Правило: list([H|T]) :- list(T)
% Подстановка: H/2, T/[]
% R_2 = { list([]) }
%
% Шаг 3. Пробуем базовый факт.
% Подцель: list([])
% Правило: list([])
% Подстановка: пустая, переменных для связывания нет
% R_3 = {} (пустая резольвента, успех)
%
% Итог: list([1,2]) истинно. Понадобилось два применения рекурсивного
% правила, по числу элементов списка, и одно применение базового факта
% на пустом остатке.

% ### Запрос: list([1,2|3]), отказ (список неправильный, хвост не []).
%
% R_0 = { list([1,2|3]) }
