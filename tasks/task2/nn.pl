% Расширение модели: оракул подбирает подстановки в цель и выбирает
% предложения программы.
% Формулировка задачи: построить предикат nn/1, который истинен, если его
% аргумент - терм вида 0, s(0), s(s(0)) и так далее, и ложен в остальных
% случаях. Построить протокол вычислений для запроса nn(X) и показать,
% откуда берутся ответы X=0, X=s(0), X=s(s(0)).

% ## Решение

% Терм 0 - базовый случай. Терм с внешним символом s сводится к своему
% аргументу, то есть к терму на один символ s короче.
nn(0).
nn(s(X)) :- nn(X).

% ## Протокол вычислений
%
% Обозначения: R_i резольвента (текущий набор подцелей) после шага i.
% Переменные предложения перед применением переименовываются, чтобы они
% не совпали с переменными запроса.

% ### Пример 1, успех на замкнутом запросе. Запрос: nn(s(s(0))).
%
% R_0 = { nn(s(s(0))) }
%
% Шаг 1. Факт nn(0) не подходит, s(s(0)) не совпадает с 0. Берем правило
% и снимаем один символ s, переходим к аргументу.
% Подцель: nn(s(s(0)))
% Правило: nn(s(X)) :- nn(X)
% Подстановка: X/s(0)
% R_1 = { nn(s(0)) }
%
% Шаг 2. Снова снимаем символ s.
% Подцель: nn(s(0))
% Правило: nn(s(X)) :- nn(X)
% Подстановка: X/0
% R_2 = { nn(0) }
%
% Шаг 3. Символы s кончились, подходит базовый факт.
% Подцель: nn(0)
% Правило: nn(0)
% Подстановка: пустая, переменных для связывания нет
% R_3 = {} (пустая резольвента, успех)
%
% Итог: nn(s(s(0))) истинно. Правило применено два раза, по количеству
% символов s в запросе.

% ### Пример 2, запрос с переменной. Запрос: nn(X).
%
% R_0 = { nn(X) }
%
% Сначала по расширенной модели. Оракул сам подбирает подстановку в цель
% и само предложение, а резолюция только проверяет догадку.
%
% Догадка 1. Оракул подставляет X/[a] и предлагает факт nn(0).
% Подцель: nn([a])
% Правило: nn(0), не подходит, [a] не совпадает с 0
% Правило: nn(s(X1)) :- nn(X1), не подходит, [a] не совпадает с s(X1)
% Результат: отказ, догадка неудачная.
%
% Догадка 2. Оракул подставляет X/0 и предлагает факт nn(0).
% Подцель: nn(0)
% Правило: nn(0)
% Подстановка: пустая
% R_1 = {} (пустая резольвента, успех)
% Результат: ответ X = 0.
%
% Настоящий Prolog оракула не имеет и заранее ничего не угадывает. Он
% оставляет X переменной и перебирает предложения сверху вниз, а ответ
% получается из унификатора. Отсюда и берутся ответы из условия.
%
% Шаг 1. Первое предложение программы - базовый факт.
% Подцель: nn(X)
% Правило: nn(0)
% Подстановка: X/0
% R_1 = {} (пустая резольвента, успех)
% Первый ответ: X = 0.
%
% При запросе следующего ответа происходит возврат к шагу 1, и там
% берется второе предложение.
%
% Шаг 1'. Применяем правило, X становится термом с одним символом s.
% Подцель: nn(X)
% Правило: nn(s(X1)) :- nn(X1)
% Подстановка: X/s(X1)
% R_1' = { nn(X1) }
%
% Шаг 2'. Для X1 снова первой пробуется база.
% Подцель: nn(X1)
% Правило: nn(0)
% Подстановка: X1/0
% R_2' = {} (пустая резольвента, успех)
% Второй ответ: X = s(0).
%
% Шаг 2''. Следующий возврат, вместо факта на подцели nn(X1) берем правило.
% Подцель: nn(X1)
% Правило: nn(s(X2)) :- nn(X2)
% Подстановка: X1/s(X2)
% R_2'' = { nn(X2) }
%
% Шаг 3''. Подцель nn(X2), правило nn(0), подстановка X2/0.
% R_3'' = {} (пустая резольвента, успех)
% Третий ответ: X = s(s(0)).
%
% Итог: ответов бесконечно много. Каждый следующий получается еще одним
% применением правила перед выходом на факт, поэтому выдается ровно
% последовательность 0, s(0), s(s(0)) и так далее, с ростом количества
% символов s.
%
% Порядок предложений здесь важен. Если поставить правило перед фактом,
% то на запрос nn(X) резольвента будет только расти: nn(X), nn(X1),
% nn(X2) и так далее, и ни одного ответа не будет.

% ### Пример 3, отказ. Запрос: nn(s(a)).
%
% R_0 = { nn(s(a)) }
%
% Шаг 1. Факт nn(0) не подходит, s(a) не совпадает с 0. Снимаем символ s.
% Подцель: nn(s(a))
% Правило: nn(s(X)) :- nn(X)
% Подстановка: X/a
% R_1 = { nn(a) }
%
% Шаг 2. Проверяем подцель nn(a).
% Подцель: nn(a)
% Правило: nn(0), не подходит, a не совпадает с 0
% Правило: nn(s(X1)) :- nn(X1), не подходит, a не совпадает с s(X1)
% Результат: отказ. Запрос nn(s(a)) ложен.
%
% По той же причине ложен и запрос nn(1): терм 1 не совпадает ни с 0,
% ни с s(X).
