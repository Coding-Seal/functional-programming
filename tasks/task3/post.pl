% Номер задачи: Задача 3
% Тема: Постфиксный обход бинарного дерева, предикат post/2
% Вычислительная модель: логическое программирование (Prolog), SLD-резолюция.
% Формулировка задачи: раскрутить вычисление запроса
% ?- post((2+3)*(4-5), L), воспроизведя рассуждения простого абстрактного
% интерпретатора, и показать, какие вершины дерева выражения и в каком
% порядке попадают в список L при постфиксном обходе.

% ## Решение

% Дерево арифметического выражения (2+3)*(4-5):
%
%          *
%        /   \
%       +     -
%      / \   / \
%     2   3 4   5
%
% Дерево можно записать термом tree(X, L, R), где X вершина, L и R
% поддеревья, а пустое дерево это void. То же дерево можно записать
% обычным арифметическим термом: вместо tree(X, L, R) пишется X(L, R),
% например tree(+, 2, 3) это 2+3. В запросе дерево дано во втором виде.
% Ниже предикат post/2 понимает обе записи.

% Запись термом tree(X, L, R). Сначала обходятся поддеревья, потом
% вершина X приписывается в конец.
% nonvar(T)/T==void: без этой проверки непривязанная переменная (лист X
% в примере 3) сама совпадает с tree(X,L,R) или void и уходит в
% бесконечную рекурсию, вместо того чтобы дойти до правила листа.
post(T, Xs) :-
    nonvar(T),
    T = tree(X, L, R),
    post(L, Ls),
    post(R, Rs),
    append(Rs, [X], Rs1),
    append(Ls, Rs1, Xs).
post(T, []) :- T == void.

% Та же обработка узла, когда дерево записано обычным термом X(L, R).
% T =.. [X, L, R] разбирает терм на вершину и два поддерева.
post(T, Xs) :-
    compound(T),
    T =.. [X, L, R],
    post(L, Ls),
    post(R, Rs),
    append(Rs, [X], Rs1),
    append(Ls, Rs1, Xs).

% Лист: несоставной терм (число, атом, переменная), кроме пустого дерева.
post(T, [T]) :-
    \+ compound(T),
    T \== void.

% append/3 стандартный предикат конкатенации списков:
%     append([], Y, Y).
%     append([H|T], Y, [H|Z]) :- append(T, Y, Z).

% ## Протокол вычислений
%
% Обозначения: R_i резольвента (текущий набор подцелей) после шага i.
% Переменные предложения перед применением переименовываются, индекс
% переменной равен номеру шага. Правило для узла дальше называется
% правилом узла, предложение post(T,[T]) правилом листа.

% ### Пример 1, основной. Запрос: post((2+3)*(4-5), L).
%
% R_0 = { post((2+3)*(4-5), L) }
%
% Шаг 1. Корень дерева это умножение, его поддеревья 2+3 и 4-5.
% Первые два предложения не подходят: (2+3)*(4-5) не совпадает ни с
% tree(X,L,R), ни с void. Берем правило узла.
% Подцель: post((2+3)*(4-5), L)
% Правило: post(T1,Xs1) :- compound(T1), T1 =.. [X1,L1,R1], post(L1,Ls1),
%          post(R1,Rs1), append(Rs1,[X1],A1), append(Ls1,A1,Xs1)
% Подстановка: T1/(2+3)*(4-5), Xs1/L
% R_1 = { compound((2+3)*(4-5)), (2+3)*(4-5) =.. [X1,L1,R1],
%         post(L1,Ls1), post(R1,Rs1), append(Rs1,[X1],A1),
%         append(Ls1,A1,L) }
%
% Шаг 2. Разбираем терм на вершину и поддеревья.
% Подцель: compound((2+3)*(4-5)) и (2+3)*(4-5) =.. [X1,L1,R1]
% Правило: встроенные предикаты compound/1 и (=..)/2
% Подстановка: X1/*, L1/2+3, R1/4-5
% R_2 = { post(2+3,Ls1), post(4-5,Rs1), append(Rs1,[*],A1),
%         append(Ls1,A1,L) }
%
% В списке пока нет ни одной вершины, L не связана. Вершина * ждет в
% подцели append(Rs1,[*],A1) и попадет в список последней.
%
% Шаг 3. Берем первую подцель, левое поддерево 2+3. Разбор тот же, что
% на шагах 1-2, поэтому дальше эти два шага объединены в один.
% Подцель: post(2+3, Ls1)
% Правило: правило узла
% Подстановка: T3/2+3, X3/+, L3/2, R3/3, Xs3/Ls1
% R_3 = { post(2,Ls3), post(3,Rs3), append(Rs3,[+],A3), append(Ls3,A3,Ls1),
%         post(4-5,Rs1), append(Rs1,[*],A1), append(Ls1,A1,L) }
%
% Шаг 4. Подцель post(2,Ls3). Терм 2 несоставной и не равен void,
% подходит правило листа. Это первая вершина, попавшая в список.
% Подцель: post(2, Ls3)
% Правило: post(T4,[T4]) :- \+ compound(T4), T4 \== void
% Подстановка: T4/2, Ls3/[2]
% R_4 = { post(3,Rs3), append(Rs3,[+],A3), append([2],A3,Ls1),
%         post(4-5,Rs1), append(Rs1,[*],A1), append(Ls1,A1,L) }
%
% Шаг 5. Так же обрабатывается второй лист, вершина 3.
% Подцель: post(3, Rs3)
% Правило: правило листа
% Подстановка: T5/3, Rs3/[3]
% R_5 = { append([3],[+],A3), append([2],A3,Ls1), post(4-5,Rs1),
%         append(Rs1,[*],A1), append(Ls1,A1,L) }
%
% Шаг 6. Оба потомка вершины + обойдены, теперь в список идет сама
% вершина +, она приписывается справа.
% Подцель: append([3],[+],A3)
% Правило: append/3
% Подстановка: A3/[3,+]
% R_6 = { append([2],[3,+],Ls1), post(4-5,Rs1), append(Rs1,[*],A1),
%         append(Ls1,A1,L) }
%
% Шаг 7. Приписываем слева список левого потомка. Левое поддерево готово.
% Подцель: append([2],[3,+],Ls1)
% Правило: append/3
% Подстановка: Ls1/[2,3,+]
% R_7 = { post(4-5,Rs1), append(Rs1,[*],A1), append([2,3,+],A1,L) }
%
% Шаги 8-12. Правое поддерево 4-5 обрабатывается точно так же, как в
% шагах 3-7: правило узла дает вершину - и листья 4 и 5, правило листа
% дает [4] и [5], затем append([5],[-],[5,-]) и append([4],[5,-],[4,5,-]).
% Подстановка: Rs1/[4,5,-]
% R_12 = { append([4,5,-],[*],A1), append([2,3,+],A1,L) }
%
% Шаг 13. Оба поддерева обойдены, в список идет корень *.
% Подцель: append([4,5,-],[*],A1)
% Правило: append/3
% Подстановка: A1/[4,5,-,*]
% R_13 = { append([2,3,+],[4,5,-,*],L) }
%
% Шаг 14. Склеиваем левую часть с остальным, получаем ответ.
% Подцель: append([2,3,+],[4,5,-,*],L)
% Правило: append/3
% Подстановка: L/[2,3,+,4,5,-,*]
% R_14 = {} (пустая резольвента, успех)
%
% Ответ: L = [2,3,+,4,5,-,*], то есть 2 3 + 4 5 - *.

% ### Раскрутка последнего append
%
% Сам список собирается предикатом append/3 по одной ячейке, слева
% направо. Распишем шаг 14 подробно.
%
% append([2,3,+],[4,5,-,*],L): правило append([H|T],Y,[H|Z]), H/2,
%     L = [2|Z1], остается append([3,+],[4,5,-,*],Z1)
% append([3,+],[4,5,-,*],Z1): H/3, Z1 = [3|Z2],
%     остается append([+],[4,5,-,*],Z2)
% append([+],[4,5,-,*],Z2): H/+, Z2 = [+|Z3],
%     остается append([],[4,5,-,*],Z3)
% append([],[4,5,-,*],Z3): факт append([],Y,Y), Z3 = [4,5,-,*]
%
% Подставляя обратно:
% L = [2|Z1] = [2|[3|Z2]] = [2|[3|[+|Z3]]] = [2|[3|[+|[4,5,-,*]]]]
%   = [2,3,+,4,5,-,*].

% ### Порядок попадания вершин в список
%
% Вызовы post/2 идут сверху вниз и слева направо, то есть вершины
% посещаются в порядке *, +, 2, 3, -, 4, 5. Но в список вершина
% попадает не тогда, когда ее посетили, а тогда, когда закончено ее
% поддерево, потому что в теле правила узла append стоит после обоих
% рекурсивных вызовов. Поэтому порядок попадания другой:
%
% 1. 2  (шаг 4, лист левого поддерева)
% 2. 3  (шаг 5, второй лист левого поддерева)
% 3. +  (шаг 6, корень левого поддерева, после обоих своих потомков)
% 4. 4  (шаг 9)
% 5. 5  (шаг 10)
% 6. -  (шаг 11, корень правого поддерева)
% 7. *  (шаг 13, корень всего дерева, последним)
%
% Это и есть постфиксный порядок: 2 3 + 4 5 - *. Такая запись совпадает
% с обратной польской записью выражения (2+3)*(4-5).

% ### Пример 2, то же дерево в записи tree(X, L, R)
%
% Запрос:
% ?- post(tree(*, tree(+, tree(2,void,void), tree(3,void,void)),
%              tree(-, tree(4,void,void), tree(5,void,void))), L).
%
% Здесь работают первые два предложения. Лист tree(2,void,void)
% обрабатывается правилом узла: post(void,[]) дважды дает Ls=[] и Rs=[],
% затем append([],[2],[2]) и append([],[2],[2]), то есть [2]. Дальше все
% повторяет пример 1, и ответ тот же: L = [2,3,+,4,5,-,*].

% ### Пример 3, выражение с переменной
%
% Запрос: ?- post(((X**3)-(5*X))+(3/2), L).
% Ответ: L = [X,3,**,5,X,*,-,3,2,/,+].
% Переменная X несоставной терм, поэтому она обрабатывается правилом
% листа и попадает в список как обычная вершина.

% ### Пример 4, отказ. Запрос: post(f(1,2,3), L).
%
% R_0 = { post(f(1,2,3), L) }
%
% Шаг 1. Проверяем все предложения.
% Подцель: post(f(1,2,3), L)
% Правило: post(tree(X,L,R),Xs), не подходит, f(1,2,3) не совпадает
%          с tree(X,L,R)
% Правило: post(void,[]), не подходит, f(1,2,3) не совпадает с void
% Правило: правило узла, голова совпадает, но тело проваливается:
%          f(1,2,3) =.. [f,1,2,3], а список [X1,L1,R1] имеет длину 3,
%          у вершины дерева должно быть ровно два поддерева
% Правило: правило листа, не подходит, условие \+ compound(f(1,2,3))
%          ложно
% Результат: отказ. Запрос post(f(1,2,3), L) ложен.
%
% По той же причине ложен запрос post(void, [void]): пустое дерево дает
% только пустой список, в правиле листа оно отсечено условием T \== void.
