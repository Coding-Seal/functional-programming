% Формулировка задачи: построить предикат list3/1, который истинен, если
% его аргумент — список из ровно трех элементов, и ложен в остальных случаях.

% ## Решение

% list3(L) истинно, если L имеет длину 3. Сводится к list3/2 со счетчиком.
list3(L) :- list3(L, 3).

% list3(List, N) истинно, если длина List равна N.
list3([], 0).
list3([_|T], N) :-
    N > 0,
    N1 is N - 1,
    list3(T, N1).

% ## Протокол вычислений
%
% Обозначения: R_i резольвента (текущий набор подцелей) после шага i.

% ### Пример 1, успех. Запрос: list3([a,b,c]).
%
% R_0 = { list3([a,b,c]) }
%
% Шаг 1. Переходим от list3/1 к list3/2 со счетчиком 3.
% Подцель: list3([a,b,c])
% Правило: list3(L,3) :- list3(L,3)
% Подстановка: L/[a,b,c]
% R_1 = { list3([a,b,c], 3) }
%
% Шаг 2. Список непуст, счетчик 3 не равен 0, снимаем голову a.
% Подцель: list3([a,b,c], 3)
% Правило: list3([_|T],N) :- N>0, N1 is N-1, list3(T,N1)
% Подстановка: T/[b,c], N/3
% R_2 = { 3>0, N1 is 3-1, list3([b,c],N1) }
%
% Шаг 3. Проверяем 3>0, условие верно, убираем его из резольвенты.
% Подцель: 3>0
% Правило: встроенный предикат (>)/2
% Подстановка: нет
% R_3 = { N1 is 3-1, list3([b,c],N1) }
%
% Шаг 4. Вычисляем N1.
% Подцель: N1 is 3-1
% Правило: встроенный предикат is/2
% Подстановка: N1/2
% R_4 = { list3([b,c], 2) }
%
% Шаг 5. Снимаем голову b, счетчик становится 1.
% Подцель: list3([b,c], 2)
% Правило: list3([_|T],N) :- N>0, N1 is N-1, list3(T,N1)
% Подстановка: T/[c], N/2
% R_5 = { 2>0, N1 is 2-1, list3([c],N1) }
%
% Шаг 6-7. Аналогично шагам 3-4: 2>0 истинно, N1 is 2-1 дает N1=1.
% R_7 = { list3([c], 1) }
%
% Шаг 8. Снимаем последнюю голову c, счетчик становится 0.
% Подцель: list3([c], 1)
% Правило: list3([_|T],N) :- N>0, N1 is N-1, list3(T,N1)
% Подстановка: T/[], N/1
% R_8 = { 1>0, N1 is 1-1, list3([],N1) }
%
% Шаг 9-10. Аналогично: 1>0 истинно, N1 is 1-1 дает N1=0.
% R_10 = { list3([], 0) }
%
% Шаг 11. Список пуст, счетчик 0, подходит базовый факт.
% Подцель: list3([], 0)
% Правило: list3([], 0)
% Подстановка: нет
% R_11 = {} (пустая резольвента, успех)
%
% Итог: list3([a,b,c]) истинно. Пустая резольвента получена после трех
% применений рекурсивного правила, по числу элементов списка.

% ### Пример 2, отказ, список короче. Запрос: list3([a,b]).
%
% R_0 = { list3([a,b]) }
% Шаг 1. Подцель list3([a,b]), правило list3(L,3):-list3(L,3), L/[a,b].
% R_1 = { list3([a,b], 3) }
% Шаг 2-4. Снимаем голову a, счетчик 3 переходит в 2.
% R_4 = { list3([b], 2) }
% Шаг 5-7. Снимаем голову b, счетчик 2 переходит в 1.
% R_7 = { list3([], 1) }
%
% Шаг 8. Список пуст, счетчик 1. Базовый факт list3([],0) не подходит,
% т.к. 1 не равно 0. Рекурсивное правило не подходит, т.к. голова [_|T]
% не совпадает с [].
% Подцель: list3([], 1)
% Правило: отсутствует
% Подстановка: нет
% Результат: отказ. Запрос list3([a,b]) ложен.

% ### Пример 3, отказ, список длиннее. Запрос: list3([a,b,c,d]).
%
% После трех применений рекурсивного правила, как в примере 1, счетчик
% становится 0, но список еще не пуст.
% R_10 = { list3([d], 0) }
%
% Шаг 11. Базовый факт list3([],0) не подходит: [] не совпадает
% с [d]. Голова рекурсивного правила совпадает, но первая подцель тела,
% 0>0, ложна.
% Подцель: list3([d], 0)
% Правило: list3([_|T],N) :- N>0, N1 is N-1, list3(T,N1)
% Подстановка: T/[d], N/0, но тело сразу проваливается
% Результат: отказ. Запрос list3([a,b,c,d]) ложен.
